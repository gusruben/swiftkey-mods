package nintype.engine.vectors

import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.Paths

/**
 * Scorecard: lists every function `../re/out/inventory.json` (the emulator
 * harness's function inventory, owned by the `re/` agent) knows about,
 * cross-references `PortRegistry` and the vector files under
 * `../re/out/vectors/`, and
 * writes `engine/SCORE.md`.
 *
 * `inventory.json` may not exist yet (the harness that produces it is
 * still being built) -- this handles that by falling back to whatever
 * `PortRegistry` and the vectors directory already know about, so the
 * scorecard is useful (if short) from day one and gets more complete as
 * `re/` comes online. Run via `./gradlew run` (see engine/README.md).
 *
 * Status per function:
 *  - **unported**: no Kotlin port registered.
 *  - **ported, no vectors yet**: registered, but no vector file exists to
 *    check it against (not one of the three statuses the task asked for,
 *    but a real, distinct state while `re/` hasn't produced vectors --
 *    called out explicitly rather than mislabeled as failing or verified).
 *  - **ported+verified**: registered, a vector file exists, every case
 *    matches bit-exactly.
 *  - **ported+failing**: registered, a vector file exists, at least one
 *    mismatch.
 */
object ScoreCard {

    data class Row(val function: String, val address: String, val status: String, val cases: Int, val notes: String)

    fun run(vectorsDir: Path, inventoryPath: Path, outPath: Path) {
        Ports.registerAll()

        // One vector file at a time: the full set is hundreds of MB of JSON, too big to hold at once.
        val summaries = summarizeVectorFiles(vectorsDir)
        val inventory = loadInventory(inventoryPath)
        val inventoryFound = inventory != null

        // Keyed by address: inventory names (from Ghidra) carry no parameter list, so overloads
        // share a name; vector names include the signature. Addresses are the same base on both.
        val summariesByAddr = summaries.filter { it.address.isNotEmpty() }.associateBy { normAddr(it.address) }

        // Functions verified only as part of a whole-system test (e.g. TrieDumpTest builds the whole
        // English trie and compares every pool byte), listed in COVERED_BY.json as {addr: "Test: why"}.
        // Reported separately from per-function vector verification.
        val coveredBy = loadCoveredBy(outPath.toAbsolutePath().parent?.resolve("COVERED_BY.json"))

        fun rowFor(name: String, s: Row?, addr: String = ""): Row = when {
            s != null && s.status != "unported" -> s
            coveredBy[normAddr(addr)] != null -> Row(name, addr, "covered by test", 0, coveredBy[normAddr(addr)]!!)
            s != null -> s
            PortRegistry.get(name) != null -> Row(name, "", "ported, no vectors yet", 0, "")
            else -> Row(name, "", "unported", 0, "")
        }

        // The worklist: inventory functions of kind "port".
        val worklist = (inventory ?: emptyList()).filter { it.kind == "port" }
        val worklistAddrs = worklist.map { normAddr(it.addr) }.toSet()
        val rows = worklist.map { rowFor(it.name, summariesByAddr[normAddr(it.addr)], it.addr) }

        // Verified work outside the worklist (libm, library code mirrored for bit-exactness, examples).
        val extraSummaries = summaries.filter { it.address.isEmpty() || normAddr(it.address) !in worklistAddrs }
        val vectorFunctions = summaries.map { it.function }.toSet()
        val extraRows = extraSummaries +
            PortRegistry.allNames().filter { it !in vectorFunctions }.map { rowFor(it, null) }

        val md = buildString {
            appendLine("# SCORE.md")
            appendLine()
            appendLine("Generated by `nintype.engine.vectors.ScoreCard`. Do not hand-edit -- rerun")
            appendLine("`./gradlew run` to regenerate (see engine/README.md).")
            appendLine()
            if (!inventoryFound) {
                appendLine("**Note:** `${inventoryPath}` not found -- function inventory limited to")
                appendLine("what's registered in `PortRegistry` and/or has a vector file. Rerun once")
                appendLine("`re/` produces `inventory.json` for the full picture.")
                appendLine()
            }
            val verified = rows.count { it.status == "ported+verified" }
            val failing = rows.count { it.status == "ported+failing" }
            val unported = rows.count { it.status == "unported" }
            val covered = rows.count { it.status == "covered by test" }
            val pct = if (rows.isEmpty()) 0.0 else 100.0 * verified / rows.size
            val pctAll = if (rows.isEmpty()) 0.0 else 100.0 * (verified + covered) / rows.size
            appendLine("**Worklist** (inventory functions of kind `port`): $verified verified by vectors, $covered covered by a whole-system test, $failing failing, $unported unported of ${rows.size} (${"%.1f".format(pct)}% vector-verified, ${"%.1f".format(pctAll)}% including test coverage). Instruction-weighted and side-effect coverage are not measured here.")
            appendLine()
            val extraVerified = extraRows.count { it.status == "ported+verified" }
            val extraFailing = extraRows.count { it.status == "ported+failing" }
            appendLine("**Outside the worklist** (libm, library code mirrored for bit-exactness, examples): $extraVerified verified, $extraFailing failing.")
            appendLine()
            if (rows.isEmpty() && extraRows.isEmpty()) {
                appendLine("_No functions known yet (no inventory.json, nothing registered, no vectors)._")
            } else {
                appendLine("| Function | Address | Status | Cases | Notes |")
                appendLine("|---|---|---|---|---|")
                // Ported first (failing, then verified), unported last.
                val order = mapOf("ported+failing" to 0, "ported+verified" to 1, "covered by test" to 2, "ported, no vectors yet" to 3, "unported" to 4)
                for (r in (rows + extraRows).sortedWith(compareBy({ order[it.status] ?: 4 }, { it.function }))) {
                    appendLine("| `${r.function}` | ${r.address.ifEmpty { "-" }} | ${r.status} | ${r.cases} | ${r.notes} |")
                }
            }
            appendLine()
        }

        outPath.parent?.let { Files.createDirectories(it) }
        Files.writeString(outPath, md)
        println(md)
        println("wrote $outPath")
    }

    /** Loads, runs and summarises each vector file in turn, keeping only the summary row. */
    private fun summarizeVectorFiles(dir: Path): List<Row> {
        if (!Files.isDirectory(dir)) return emptyList()
        val paths = Files.list(dir).use { stream -> stream.filter { it.toString().let { n -> n.endsWith(".json") || n.endsWith(".json.gz") } }.sorted().toList() }
        return paths.mapNotNull { path ->
            val file = try {
                VectorFile.load(path)
            } catch (e: Exception) {
                System.err.println("ScoreCard: skipping unparsable vector file $path: ${e.message}")
                return@mapNotNull null
            }
            val adapter = PortRegistry.get(file.function)
            when {
                adapter == null -> Row(file.function, file.address, "unported", file.cases.size, "vectors exist")
                file.function in PortRegistry.duplicates ->
                    Row(file.function, file.address, "ported+failing", file.cases.size,
                        "registered twice: keep one port (see CLAIMS.md)")
                else -> {
                    val result = VectorRunner.runSuite(file, adapter)
                    if (result.passed) Row(file.function, file.address, "ported+verified", file.cases.size, "")
                    else Row(file.function, file.address, "ported+failing", file.cases.size,
                        "${result.mismatches.size} mismatch(es), see test output")
                }
            }
        }
    }

    /** Reads COVERED_BY.json ({addr: "TestName: reason"}); empty if absent. */
    private fun loadCoveredBy(path: Path?): Map<String, String> {
        if (path == null || !Files.exists(path)) return emptyMap()
        return try {
            val o = Json.parse(Files.readString(path)).asObjectOrNull() ?: return emptyMap()
            o.mapNotNull { (k, v) -> v.asStringOrNull()?.let { normAddr(k) to it } }.toMap()
        } catch (e: Exception) {
            System.err.println("ScoreCard: COVERED_BY.json unparsable (${e.message}); ignoring")
            emptyMap()
        }
    }

    data class InventoryFn(val name: String, val addr: String, val kind: String)

    private fun normAddr(a: String): String = a.lowercase().removePrefix("0x").trimStart('0')

    /** Reads `{"functions": [{"name", "addr", "kind"}, ...]}`; null if absent or unparsable. */
    private fun loadInventory(path: Path): List<InventoryFn>? {
        if (!Files.exists(path)) return null
        return try {
            val root = Json.parse(Files.readString(path))
            val items = (root["functions"] as? JsonValue.JArray)?.items ?: return null
            items.mapNotNull { f ->
                val o = f.asObjectOrNull() ?: return@mapNotNull null
                val name = o["name"]?.asStringOrNull() ?: return@mapNotNull null
                InventoryFn(name, o["addr"]?.asStringOrNull() ?: "", o["kind"]?.asStringOrNull() ?: "port")
            }
        } catch (e: Exception) {
            System.err.println("ScoreCard: ${path} exists but could not be parsed (${e.message}); treating as absent")
            null
        }
    }
}

fun main(args: Array<String>) {
    val vectorsDir = Paths.get(args.getOrElse(0) { "../re/out/vectors" })
    val inventoryPath = Paths.get(args.getOrElse(1) { "../re/out/inventory.json" })
    val outPath = Paths.get(args.getOrElse(2) { "SCORE.md" })
    ScoreCard.run(vectorsDir, inventoryPath, outPath)
}
